"""Write evidence/gate2.json from a Gate 2 run (02-live-ingestion.md §9).

    python tools/gate2_evidence.py FETCHER_ROOT LIVE_OUT WORK_DIR OUT_FILE

Called by tools/gate2.sh, which runs every check and records each exit code in
WORK_DIR/checks.tsv. Criterion 6 asks for the gate1.json fields (commit, config
hash, input manifest, check results, pass/fail) plus the fetch log's SHA-256
and the `available_at` manifest; it also embeds the delay report (criterion 5).

Refuses to run unless GITHUB_ACTIONS=true (criterion 6: CI only).
Standard library only; imports neither implementation.
"""

import hashlib
import json
import sys
from pathlib import Path

from gate1_evidence import REPO, ci_from_env, git_commit, hour_file, hours, read_checks, registry_hours, sha256

CONFIG = REPO / "tools" / "gate2_config.json"
DELAY_REPORT = REPO / "evidence" / "delay-report.json"  # written by tools/gate2.sh
# Every §9 criterion and the checks (names in checks.tsv) that must all pass for it.
CRITERIA = {
    "1_every_hour_accounted": ["fetch_log"],
    "2_live_equals_replay": ["pipeline_replay", "live_digest", "compare_live_replay"],
    "3_pipeline_equals_reference": ["fixtures", "archive_input", "reference_run", "compare_reference_live"],
    "4_fetch_log_consistency": ["fetch_log"],
    "5_delay_report": ["delay_report"],
}
CONFIG_FILES = ["tools/gate2_config.json", "02-live-ingestion.md", "01-event-semantics.md", "requirements.txt"]


def build(root, live, work_dir, ci):
    config = json.loads(CONFIG.read_text())
    window = list(hours(config["window_start"], config["window_end"]))
    files = [work_dir / "input" / hour_file(h) for h in window]
    manifest = [{"file": f.name, "sha256": sha256(f) if f.exists() else None} for f in files]

    checks = read_checks(work_dir)
    criteria = {c: all(checks.get(n, {}).get("pass", False) for n in names)
                for c, names in CRITERIA.items()}
    criteria["1_every_hour_accounted"] &= registry_hours(live / "registry.csv") == window
    delay_report = json.loads(DELAY_REPORT.read_text()) if DELAY_REPORT.exists() else None
    criteria["5_delay_report"] &= bool(delay_report and delay_report["proposed_L_hours"] is not None)
    criteria["6_generated_by_ci"] = ci is not None

    available_at = work_dir / "available_at.csv"
    config_hashes = {f: sha256(REPO / f) for f in CONFIG_FILES}
    return {
        "commit": git_commit(),
        "ci": ci,
        "config": config,
        "config_files": config_hashes,
        "config_hash": hashlib.sha256(json.dumps(config_hashes, sort_keys=True).encode()).hexdigest(),
        "input_manifest": manifest,
        "fetch_log_sha256": sha256(root / "fetch_log.csv"),
        "available_at_manifest": available_at.read_text().splitlines() if available_at.exists() else None,
        "delay_report": delay_report,
        "checks": checks,
        "criteria": criteria,
        "pass": all(criteria.values()),
    }


def main(argv):
    if len(argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    ci = ci_from_env()
    if ci is None:
        print("refusing: 02 §9 criterion 6 says Gate 2 evidence is generated by CI only", file=sys.stderr)
        return 2
    evidence = build(Path(argv[1]), Path(argv[2]), Path(argv[3]), ci)
    out = Path(argv[4])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps({"pass": evidence["pass"], "criteria": evidence["criteria"]}, indent=2))
    return 0 if evidence["pass"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
