"""Write evidence/gate1.json from a Gate 1 run (01-event-semantics.md §8).

    python tools/gate1_evidence.py INPUT_DIR WORK_DIR OUT_FILE

Called by tools/gate1.sh, which runs every check and records each exit code in
WORK_DIR/checks.tsv (name<TAB>exit_code). This script adds what §8 criterion 6
asks for: commit SHA, config hash, input manifest (file name + SHA-256), every
check result, and overall pass/fail.

Criterion 6 says the evidence is generated by CI only, so this refuses to run
unless GITHUB_ACTIONS=true, and records the run's URL.

Standard library only. Must not import anything from the pipeline codebase.
"""

import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CONFIG = REPO / "tools" / "gate1_config.json"
# Every §8 criterion and the checks (names in checks.tsv) that must all pass for it.
CRITERIA = {
    "1_fixtures": ["fixtures"],
    "2_month_equal": ["reference_run", "pipeline_batch", "compare_reference_batch"],
    "3_replay_equals_batch": ["pipeline_replay", "replay_digest", "compare_batch_replay"],
    "4_source_reconciliation": ["bigquery", "reconcile"],
}
# Files whose content defines the run; their hashes make up the config hash.
CONFIG_FILES = ["tools/gate1_config.json", "01-event-semantics.md", "requirements.txt",
                "tools/bigquery/type_by_hour.sql", "tools/bigquery/ids_by_hour.sql",
                "tools/bigquery/stars.sql"]


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def hours(start, end):
    t, end = (datetime.strptime(x, "%Y-%m-%dT%H:%M:%SZ") for x in (start, end))
    while t <= end:
        yield t.strftime("%Y-%m-%dT%H:00:00Z")
        t += timedelta(hours=1)


def hour_file(hour):
    """GH Archive file name for an hour: 2026-09-01T05:00:00Z -> 2026-09-01-5.json.gz"""
    return f"{hour[:10]}-{int(hour[11:13])}.json.gz"


def build(input_dir, work_dir, ci):
    config = json.loads(CONFIG.read_text())
    window = list(hours(config["window_start"], config["window_end"]))
    manifest = [{"file": f, "sha256": sha256(input_dir / f) if (input_dir / f).exists() else None}
                for f in map(hour_file, window)]

    checks = {}
    for line in (work_dir / "checks.tsv").read_text().splitlines():
        name, code = line.split("\t")
        checks[name] = {"exit": int(code), "pass": code == "0"}
    criteria = {c: all(checks.get(n, {}).get("pass", False) for n in names)
                for c, names in CRITERIA.items()}

    registry = work_dir / "pipeline" / "registry.csv"
    listed = [l.split(",")[0] for l in registry.read_text().splitlines()[1:]] if registry.exists() else []
    criteria["5_registry_full_month"] = sorted(listed) == window
    criteria["6_generated_by_ci"] = ci is not None

    recon = work_dir / "reconcile" / "reconciliation.json"
    config_hashes = {f: sha256(REPO / f) for f in CONFIG_FILES}
    return {
        "commit": subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"],
                                 capture_output=True, text=True).stdout.strip(),
        "ci": ci,
        "config": config,
        "config_files": config_hashes,
        "config_hash": hashlib.sha256(json.dumps(config_hashes, sort_keys=True).encode()).hexdigest(),
        "input_manifest": manifest,
        "checks": checks,
        "reconciliation": json.loads(recon.read_text()) if recon.exists() else None,
        "criteria": criteria,
        "pass": all(criteria.values()),
    }


def main(argv):
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    if os.environ.get("GITHUB_ACTIONS") != "true":
        print("refusing: §8 criterion 6 says Gate 1 evidence is generated by CI only", file=sys.stderr)
        return 2
    env = os.environ
    ci = {"run_url": f"{env['GITHUB_SERVER_URL']}/{env['GITHUB_REPOSITORY']}/actions/runs/{env['GITHUB_RUN_ID']}",
          "runner": env.get("RUNNER_NAME"), "workflow": env.get("GITHUB_WORKFLOW")}
    evidence = build(Path(argv[1]), Path(argv[2]), ci)
    out = Path(argv[3])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps({"pass": evidence["pass"], "criteria": evidence["criteria"]}, indent=2))
    return 0 if evidence["pass"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
